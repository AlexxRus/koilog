def _prov(
    source_ids: tuple[int, ...],
    basis: str,
    level: str,
    numbers: str,
    numbers_from: str,
    value_origin: str,
    note: str = "",
) -> dict[str, object]:
    """Собрать запись провенанса пары «профиль × мышца».

    Поля: ``source_ids`` (номера 1–27), ``basis`` (основание из §3.4),
    ``doi_journal`` (DOI либо строка журнала), ``extracted_at``, ``level``,
    ``numbers`` (OA/PDF/override/—), ``numbers_from``, ``value_origin``,
    ``note``. Пустых строк нет: у C-экс/«не измерено» журнал заменён явной
    пометкой «экспертная модель v1».
    """
    if source_ids:
        journal = "; ".join(_JOURNALS[i] for i in source_ids)
    else:
        journal = "экспертная модель v1 (PW-99, 2026-11-05)"
    return {
        "source_ids": tuple(source_ids),
        "basis": basis,
        "doi_journal": journal,
        "extracted_at": EXTRACTED_AT,
        "level": level,
        "numbers": numbers,
        "numbers_from": numbers_from,
        "value_origin": value_origin,
        "note": note,
    }


