def _pool_rows(conn: sqlite3.Connection) -> list[sqlite3.Row]:
    """Пул §2.4: фильтры sets + профиль + не статика + не кардио."""
    from . import muscles, taxonomy

    rows = conn.execute(
        """
        SELECT date, exercise, weight, reps, koi, is_gravitron
          FROM sets
         WHERE date IS NOT NULL
           AND is_warmup = 0
           AND skipped = 0
           AND is_outlier = 0
           AND is_foreign = 0
        """
    ).fetchall()

    pool = []
    for r in rows:
        prof = muscles.muscles_of(r["exercise"])
        if prof is None or muscles.DASH in prof.muscles or prof.is_static:
            continue
        if taxonomy.mode_of(r["exercise"]) is taxonomy.Mode.CARDIO:
            continue
        pool.append(r)
    return pool


def _pool_stats(pool: list[sqlite3.Row]) -> dict[str, float]:
    """Отпечаток пула: дни, E, КОИ, подходы без E, гравитрон."""
    days = set()
    days_with_e = set()
    e_total = 0.0
    koi_total = 0.0
    without_e = 0
    grav_sets = 0
    grav_kg = 0.0

    for r in pool:
        days.add(r["date"])
        e = 0.0
        if r["weight"] is not None and r["reps"] is not None:
            e = float(r["weight"]) * float(r["reps"])
        else:
            without_e += 1
        if e > 0:
            e_total += e
            days_with_e.add(r["date"])
        if r["koi"] is not None:
            koi_total += float(r["koi"])
        if r["is_gravitron"]:
            grav_sets += 1
            grav_kg += e

    return {
        "pool": len(pool),
        "days": len(days),
        "days_with_E": len(days_with_e),
        "sets_without_E": without_e,
        "E_total": e_total,
        "koi_total": koi_total,
        "gravitron_sets": grav_sets,
        "gravitron_kg": grav_kg,
    }


def delta_v1_to_v2(conn: sqlite3.Connection) -> str:
    """Отчёт дельты v1→v2 на живой базе (display-only, только чтение).

    Печатает:
      1) пары, сдвинутые числами литературы (v1 → v2, источник, уровень);
      2) пары, оставшиеся v1, с причиной;
      3) overrides тяг (не сдвинулись: числа ждут PDF/классов тяг);
      4) сверку с отпечатком §2.4 (расхождение = ошибка пула/фильтров);
      5) суммы по мышцам v1 → v2 (кг и КОИ), окно 90 дней.

    Args:
        conn: подключение к базе тренировок (read-only по смыслу; запись нет).

    Returns:
        Строка Markdown-отчёта.
    """
    pool = _pool_rows(conn)
    stats = _pool_stats(pool)
    anchor = max((r["date"] for r in pool), default="—")

    lines = [
        "# PW-105: дельта v1 → v2 (sEMG-модель, %MVC)",
        "",
        f"anchor={anchor}  pool={int(stats['pool'])}  days={int(stats['days'])}  "
        f"sets_without_E={int(stats['sets_without_E'])}  "
        f"E_total={stats['E_total']:.1f}",
        "v2 — относительная активация, %MVC; это не «доля силы». "
        "Тоннаж × доля — оценка-прокси перегрузки.",
        "Методология: Vigotsky et al., 2017 (№4); Felici & Del Vecchio, 2020 (№5).",
        "",
        "## 1. Пары, сдвинутые числами литературы",
        "",
        "| # | профиль | мышца | v1 | v2 | Δ | уровень | числа | источник | примечание |",
        "|---|---|---|---:|---:|---:|---|---|---|---|",
    ]

    moved = 0
    stayed = 0
    pair_no = 0
    for profile, role in _SHARES_V1.items():
        v1 = _shares(profile, role)
        v2 = _shares_v2(profile)
        for muscle in profile:
            pair_no += 1
            old, new = v1[muscle], v2[muscle]
            prov = _PROVENANCE_V2[(profile, muscle)]
            if abs(new - old) > 1e-9:
                moved += 1
                lines.append(
                    f"| {pair_no} | {'|'.join(profile)} | {muscle} | {old:.4f} | "
                    f"{new:.4f} | {new - old:+.4f} | {prov['level']} | "
                    f"{prov['numbers']} | {prov['numbers_from']} | {prov['note']} |"
                )

    lines.extend([
        "",
        f"**Сдвинуто {moved} пар из {pair_no}.** Правило §1 «Методики»: нормировка "
        "%MVC внутри статьи → n-взвешенное среднее → >20 п.п. медиана + конфликт.",
        "",
        "## 2. Пары, оставшиеся v1 (число не выписано / PDF / C / «не измерено»)",
        "",
        "| # | профиль | мышца | v1 = v2 | уровень | числа | почему |",
        "|---|---|---|---:|---|---|---|",
    ])

    for profile, role in _SHARES_V1.items():
        v1 = _shares(profile, role)
        v2 = _shares_v2(profile)
        for muscle in profile:
            old, new = v1[muscle], v2[muscle]
            if abs(new - old) <= 1e-9:
                stayed += 1
                prov = _PROVENANCE_V2[(profile, muscle)]
                lines.append(
                    f"| {stayed} | {'|'.join(profile)} | {muscle} | {old:.4f} | "
                    f"{prov['level']} | {prov['numbers']} | {prov['basis']} |"
                )

    lines.extend([
        "",
        "## 3. Overrides тяг (базовая строка не применяется на живой базе)",
        "",
        "| группа | мышца | v1 | v2 | Δ | уровень | числа |",
        "|---|---|---:|---:|---:|---|---|",
    ])

    for (group, profile), v1_role in _GROUP_OVERRIDES.items():
        v1 = _shares(profile, v1_role)
        v2 = _normalize(_SHARES_V2_OVERRIDES[(group, profile)])
        prov = _OVERRIDE_PROVENANCE_V2[(group, profile)]
        for muscle in profile:
            lines.append(
                f"| {group} | {muscle} | {v1[muscle]:.4f} | {v2[muscle]:.4f} | "
                f"{v2[muscle] - v1[muscle]:+.4f} | {prov['level']} | {prov['numbers']} |"
            )

    v1_kg, v1_koi, v1_sets = totals_by_muscle(conn, bucket="all", version="v1")
    v2_kg, v2_koi, v2_sets = totals_by_muscle(conn, bucket="all", version="v2")
    v1_kg90, v1_koi90, v1_sets90 = totals_by_muscle(conn, bucket="90", version="v1")
    v2_kg90, v2_koi90, v2_sets90 = totals_by_muscle(conn, bucket="90", version="v2")
    residual_v1, _days_v1 = check_invariant(conn, version="v1")
    residual_v2, _days_v2 = check_invariant(conn, version="v2")

    lines.extend([
        "",
        "## 4. Сверка с отпечатком §2.4 (v1 обязан воспроизводить; "
        "расхождение = ошибка пула/фильтров)",
        "",
        "| величина | §2.4 | v1 сейчас | Δ |",
        "|---|---:|---:|---:|",
    ])

    checks = [
        ("pool", stats["pool"], 0),
        ("days", stats["days"], 0),
        ("days_with_E", stats["days_with_E"], 0),
        ("sets_without_E", stats["sets_without_E"], 0),
        ("E_total", stats["E_total"], 1),
        ("koi_total", stats["koi_total"], 4),
        ("residual", residual_v1, 6),
        ("gravitron_sets", stats["gravitron_sets"], 0),
        ("gravitron_kg", stats["gravitron_kg"], 1),
        ("bucket90_sets", sum(v1_sets90.values()), 2),
        ("bucket90_kg", sum(v1_kg90.values()), 1),
        ("bucket90_koi", sum(v1_koi90.values()), 4),
        ("bucket90_muscles", sum(1 for v in v1_sets90.values() if v > 0), 0),
    ]
    mismatch: list[str] = []
    for name, actual, digits in checks:
        base = _BASELINE_V1[name]
        delta = float(actual) - base
        tolerance = 0.0 if digits == 0 else (0.5 * 10 ** (-digits) if digits >= 1 else 1e-9)
        flag = "" if abs(delta) <= max(tolerance, 1e-6) else "  ← РАСХОЖДЕНИЕ"
        if flag:
            mismatch.append(name)
        if digits == 0:
            lines.append(f"| {name} | {base:,.0f} | {float(actual):,.0f} | {delta:+,.0f}{flag} |")
        else:
            lines.append(f"| {name} | {base:,.{digits}f} | {float(actual):,.{digits}f} | "
                         f"{delta:+,.{digits}f}{flag} |")

    if mismatch:
        lines.append("")
        lines.append("**ВНИМАНИЕ:** v1 не воспроизводит отпечаток §2.4 по: "
                     + ", ".join(mismatch) + " — проверить пул/фильтры (не числа v2).")

    lines.extend([
        "",
        "## 5. Суммы по мышцам: v1 → v2 (all)",
        "",
        "| мышца | v1 кг | v2 кг | Δ кг | Δ % | v1 КОИ | v2 КОИ | v1 подх. | v2 подх. |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ])

    for muscle in sorted(set(v1_kg) | set(v2_kg)):
        a_kg, b_kg = v1_kg.get(muscle, 0.0), v2_kg.get(muscle, 0.0)
        pct = (b_kg - a_kg) / a_kg * 100 if a_kg else 0.0
        lines.append(
            f"| {muscle} | {a_kg:,.1f} | {b_kg:,.1f} | {b_kg - a_kg:+,.1f} | "
            f"{pct:+.1f}% | {v1_koi.get(muscle, 0.0):,.2f} | {v2_koi.get(muscle, 0.0):,.2f} | "
            f"{v1_sets.get(muscle, 0.0):,.2f} | {v2_sets.get(muscle, 0.0):,.2f} |"
        )
    lines.append(
        f"| **СУММА** | **{sum(v1_kg.values()):,.1f}** | **{sum(v2_kg.values()):,.1f}** | "
        f"**{sum(v2_kg.values()) - sum(v1_kg.values()):+,.1f}** | | "
        f"**{sum(v1_koi.values()):,.4f}** | **{sum(v2_koi.values()):,.4f}** | "
        f"**{sum(v1_sets.values()):,.2f}** | **{sum(v2_sets.values()):,.2f}** |"
    )

    lines.extend([
        "",
        "## 6. Окно 90 дней: v1 → v2",
        "",
        "| мышца | v1 кг | v2 кг | Δ кг | Δ % |",
        "|---|---:|---:|---:|---:|",
    ])
    for muscle in sorted(set(v1_kg90) | set(v2_kg90)):
        a_kg, b_kg = v1_kg90.get(muscle, 0.0), v2_kg90.get(muscle, 0.0)
        pct = (b_kg - a_kg) / a_kg * 100 if a_kg else 0.0
        lines.append(f"| {muscle} | {a_kg:,.1f} | {b_kg:,.1f} | {b_kg - a_kg:+,.1f} | {pct:+.1f}% |")
    lines.append(
        f"| **СУММА** | **{sum(v1_kg90.values()):,.1f}** | **{sum(v2_kg90.values()):,.1f}** | "
        f"**{sum(v2_kg90.values()) - sum(v1_kg90.values()):+,.1f}** | |"
    )

    lines.extend([
        "",
        f"Инвариант: residual v1 = {residual_v1:.6f}, residual v2 = {residual_v2:.6f} "
        "(Σ(доля×E) = E для каждого подхода).",
        "Данные не пересчитывались: E = stored weight × reps (канон RM-98), "
        "база только читается.",
    ])
    return "\n".join(lines)


def totals_by_muscle(
    conn: sqlite3.Connection,
    bucket: str = "all",
    since: str | None = None,
    include_gravitron: bool = True,
    version: str = "v1",
) -> tuple[collections.Counter, collections.Counter, collections.Counter]:
    """Агрегация kg/koi/sets по мышцам.

    Args:
        conn: SQLite connection to the training database.
        bucket: 'all' или '90' (последние 90 дней от anchor).
        since: явная дата начала окна (перекрывает bucket='90').
        include_gravitron: включать ли гравитрон в расчёт (по умолчанию да).
        version: "v1" (по умолчанию — контракт отката) или "v2".

    Returns:
        (kg_counter, koi_counter, sets_counter) — три Counter по 17 мышцам.

    Raises:
        ValueError: если нет шаблона для профиля упражнения.

    Примечание:
        v2 — относительная активация, %MVC (не «доля силы»).
        Тоннаж × доля — оценка-прокси перегрузки.
    """
    pool = _pool_rows(conn)
    if not pool:
        return collections.Counter(), collections.Counter(), collections.Counter()

    anchor_date = max(r["date"] for r in pool)

    if since is None and bucket == "90":
        anchor = date_cls.fromisoformat(anchor_date)
        since = (anchor - timedelta(days=89)).isoformat()

    kg: collections.Counter = collections.Counter()
    koi: collections.Counter = collections.Counter()
    sets_cnt: collections.Counter = collections.Counter()

    for r in pool:
        if since and r["date"] < since:
            continue
        if not include_gravitron and r["is_gravitron"]:
            continue

        sh = share_of(r["exercise"], version=version)
        if sh is None:
            raise ValueError(f"No share template for exercise: {r['exercise']}")

        e = 0.0
        if r["weight"] is not None and r["reps"] is not None:
            e = float(r["weight"]) * float(r["reps"])
        k_val = float(r["koi"]) if r["koi"] is not None else 0.0

        for m, w in sh.items():
            kg[m] += e * w
            koi[m] += k_val * w
            sets_cnt[m] += w

    return kg, koi, sets_cnt


def check_invariant(conn: sqlite3.Connection, version: str = "v1") -> tuple[float, int]:
    """Проверить инвариант Σ(share×E) = E по всем подходам.

    Args:
        conn: SQLite connection to the training database.
        version: "v1" (по умолчанию) или "v2".

    Returns:
        (total_residual, days_with_E) — общая ошибка и число дней с E.

    Expected:
        total_residual ≈ 0.0 (точка счёта).
    """
    kg_by_day: dict[str, float] = {}
    e_by_day: dict[str, float] = {}

    for r in _pool_rows(conn):
        sh = share_of(r["exercise"], version=version)
        if sh is None:
            continue

        e = 0.0
        if r["weight"] is not None and r["reps"] is not None:
            e = float(r["weight"]) * float(r["reps"])

        day = r["date"]
        kg_by_day.setdefault(day, 0.0)
        e_by_day.setdefault(day, 0.0)
        if e > 0:
            kg_by_day[day] += e * sum(sh.values())
            e_by_day[day] += e

    worst = 0.0
    for day, e_total in e_by_day.items():
        resid = abs(kg_by_day[day] - e_total)
        if resid > worst:
            worst = resid

    days_with_e = sum(1 for value in e_by_day.values() if value > 0)
    return worst, days_with_e
