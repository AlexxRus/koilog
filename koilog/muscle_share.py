def _shares(profile: tuple[str, ...], role: tuple[float, ...]) -> dict[str, float]:
    """Нормализовать роли к долям (Σ=1)."""
    total = sum(role)
    return {m: w / total for m, w in zip(profile, role)}


def _normalize(weights: dict[str, float]) -> dict[str, float]:
    """Нормировать веса относительной активации к Σ=1."""
    total = sum(weights.values())
    return {m: w / total for m, w in weights.items()}


def _shares_v2(profile: tuple[str, ...]) -> dict[str, float]:
    """Доли v2 профиля, нормированные к Σ=1 (без группового override)."""
    return _normalize(_SHARES_V2[profile])


def share_of(exercise: str, version: str = "v1") -> dict[str, float] | None:
    """Доли мышц упражнения по таблице v1 или v2.

    Args:
        exercise: имя упражнения.
        version: "v1" (по умолчанию — контракт отката PW-99) или "v2".

    Returns:
        Словарь {мышца: доля} или None, если упражнение не имеет профиля.

    Примечание:
        v2 — **относительная активация, %MVC**, не «доля силы»; см.
        Vigotsky et al., 2017 (№4) и Felici & Del Vecchio, 2020 (№5).
        Для тяг сначала применяется групповой override (вертикальная
        5/2/2/1, горизонтальная 4/3/2/1), затем базовая строка профиля.
    """
    from . import muscles, taxonomy

    prof = muscles.muscles_of(exercise)
    if prof is None:
        return None
    profile = prof.muscles
    group = taxonomy.group_of(exercise).name

    if version == "v1":
        role = _GROUP_OVERRIDES.get((group, profile))
        if role is None:
            role = _SHARES_V1.get(profile)
        if role is None:
            return None
        return _shares(profile, role)

    override = _SHARES_V2_OVERRIDES.get((group, profile))
    if override is not None:
        return _normalize(override)
    if profile not in _SHARES_V2:
        return None
    return _shares_v2(profile)


def _levels_of(profile: tuple[str, ...]) -> tuple[str, str]:
    """Уровень и статус чисел профиля: уникальные значения через «/»."""
    levels: list[str] = []
    numbers: list[str] = []
    for muscle in profile:
        prov = _PROVENANCE_V2.get((profile, muscle), {})
        level = str(prov.get("level", "—"))
        num = str(prov.get("numbers", "—"))
        if level not in levels:
            levels.append(level)
        if num not in numbers:
            numbers.append(num)
    return "/".join(levels), "/".join(numbers)


def _journals_of(profile: tuple[str, ...]) -> str:
    """DOI/журналы профиля: уникальные строки источников через «; »."""
    seen: list[str] = []
    for muscle in profile:
        prov = _PROVENANCE_V2.get((profile, muscle), {})
        ids = tuple(prov.get("source_ids") or ())
        for i in ids:
            journal = _JOURNALS[i]
            if journal not in seen:
                seen.append(journal)
    if not seen:
        return "экспертная модель v1 (PW-99)"
    return "; ".join(seen)


