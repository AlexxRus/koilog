# Нормализация имён
# --------------------------------------------------------------------------

#: Пробелы, которые встречаются в выгрузках: обычный, неразрывный (NBSP),
#: узкий неразрывный (\u202f - он же в датах отчёта) и волосяной.
#: Внимание: значение замены - именно пробел. ``dict.fromkeys`` дал бы ``None``,
#: а ``str.translate`` с ``None`` не заменяет символ, а удаляет его.
_SPACE_CHARS = (
    0x00A0,
    0x202F,
    0x2009,
    0x2007,
    0x2005,
    0x2000,
    0x2001,
    0x2002,
    0x2003,
    0x2004,
    0x2006,
    0x2008,
    0x200A,
)
_SPACES = {codepoint: " " for codepoint in _SPACE_CHARS}
_WHITESPACE = re.compile(r"\s+")


def normalize(name: str | None) -> str:
    """Привести название упражнения или тренировки к сравнимому виду.

    Убирает все виды неразрывных пробелов, схлопывает повторы пробелов и
    срезает края. Регистр не трогает - в данных он осмысленный
    (``Скручивания`` и ``скручивания`` в отчёте, ``День 1`` и ``день 1``).

    В 119 строках выгрузки журнала в названиях тренировок стоит NBSP
    (``Full Body 5x5``, ``Спина 1``, ``Грудь / Ноги``), а в одной - двойной
    пробел (``Ноги  / Спина``). Без этого группировка по названию молча
    разваливается на почти-одинаковые группы.
    """
    if name is None:
        return ""
    text = unicodedata.normalize("NFC", str(name))
    text = text.translate(_SPACES)
    return _WHITESPACE.sub(" ", text).strip()


#: Упражнения, где запись может содержать вес собственного тела.
#: Собирается из словарей выше, чтобы не расходиться с ними при правках.
BODYWEIGHT_EXERCISES: frozenset[str] = frozenset(
    name
    for name in EXERCISE_GROUP
    if WEIGHT_MODE_OVERRIDE.get(name, GROUPS[EXERCISE_GROUP[name]].weight_mode)
    is not WeightMode.ABSOLUTE
)

#: Ключи для быстрой проверки «это упражнение на время».
_TIMED_KEYS: frozenset[str] = frozenset(
    normalize(n).casefold() for n in TIMED_EXERCISES
)


# --------------------------------------------------------------------------
# Доступ
# --------------------------------------------------------------------------

_INDEX: dict[str, str] = {}


def _build_index() -> dict[str, str]:
    if not _INDEX:
        for name, group in EXERCISE_GROUP.items():
            key = normalize(name).casefold()
            if key in _INDEX and _INDEX[key] != group:
                raise ValueError(f"двойное сопоставление: {name}")
            _INDEX[key] = group
    return _INDEX


def group_of(name: str | None) -> Group:
    """Группа по исходному названию. ``UNKNOWN``, если имени нет в словаре."""
    key = normalize(name).casefold()
    if not key:
        return UNKNOWN
    group = GROUPS.get(_build_index().get(key, ""))
    return group if group is not None else UNKNOWN


def weight_mode_of(name: str | None) -> WeightMode:
    """Как записан вес в этом упражнении."""
    key = normalize(name).casefold()
    if not key:
        return WeightMode.ABSOLUTE
    canonical = _canonical_name(key)
    override = WEIGHT_MODE_OVERRIDE.get(canonical)
    if override is not None:
        return override
    return group_of(canonical).weight_mode


def _canonical_name(key: str) -> str:
    """Вернуть канонический вид имени (исходный регистр) по ключу сравнения."""
    for name in EXERCISE_GROUP:
        if normalize(name).casefold() == key:
            return name
    return key


def is_bodyweight_based(name: str | None) -> bool:
    """Упражнение выполняется на собственном теле (с жилетом или без)."""
    return weight_mode_of(name) is not WeightMode.ABSOLUTE


def mode_of(name: str | None) -> Mode | None:
    """Режим нагрузки упражнения (E1, D11-a=E): железо / своё тело / кардио.

    Единственная точка ветвления для погрупповой аналитики (``health.groups``).
    Режим выводится **кодом** из таксономии, а не хранится ручной колонкой:

    * имя не в словаре → ``None`` (**не** тихий дефолт «железо»): агрегат
      обязан упасть со списком имён, а не отнести неизвестное к ветке;
    * запись веса конкретного имени не ``ABSOLUTE`` (переопределение или
      группа) → ``BODYWEIGHT``. Это держит смешанные группы честными:
      ``Приседания`` (жилет) и ``Подтягивания`` (суммарный вес тела) уходят в
      «своё тело», хотя их группы — железо;
    * иначе берётся ``Group.mode`` (кардио помечено на группе явно).

    Ровно один режим на упражнение: функция детерминирована, а двухрежимность
    (напр. и железо, и своё тело) — отдельная развилка, а не молчаливый выбор.
    """
    group = group_of(name)
    if group is UNKNOWN:
        return None
    if weight_mode_of(name) is not WeightMode.ABSOLUTE:
        return Mode.BODYWEIGHT
    return group.mode


def counts_rm_of(name: str | None) -> bool:
    """Считается ли для этого упражнения 1RM.

    Неизвестные имена (``UNKNOWN``) проходят считанными: упражнение может
    оказаться нераспознанным, но это не повод лишать его метрик. Группы без
    1RM перечислены явно, см. ``NO_RM_GROUPS``.
    """
    return group_of(name).counts_rm


def is_timed_exercise(name: str | None) -> bool:
    """Упражнение измеряется в секундах, а не в повторах."""
    key = normalize(name).casefold()
    return bool(key) and key in _TIMED_KEYS


def unmapped(names: Iterable[str | None]) -> list[str]:
    """Уникальные имена из входного списка, которых нет в словаре.

    Печатается при каждой загрузке. Пустой список - норма; непустой
    означает, что в выгрузке появилось упражнение, которому ещё не назначена
    группа, и его 1RM не попадёт в скользящее средние.
    """
    seen: dict[str, str] = {}
    for name in names:
        key = normalize(name)
        if not key or group_of(key) is not UNKNOWN:
            continue
        seen.setdefault(key, key)
    return sorted(seen)
