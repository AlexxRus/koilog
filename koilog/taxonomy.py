class Mode(StrEnum):
    """Режим нагрузки группы: какая метрика у неё каноническая (E1, D11-a=E).

    Режим — это **не** способ записи веса (:class:`WeightMode`) и не
    ``equipment``: это ответ на вопрос «чем измеряется нагрузка». Задан
    **явно** на каждой группе, а не выведен из флагов, чтобы новую группу
    нельзя было завести, забыв режим (``Group`` требует его).

    ``IRON``
        Железо: есть вес, каноническая метрика — тоннаж (``weight*reps``).
    ``BODYWEIGHT``
        Своё тело: вес тела/жилет, метрика — **подходы** (тоннаж
        систематически обнуляется: ``weight`` пуст или телесный).
    ``CARDIO``
        Кардио: метрика — **время** и дистанция, тоннаж 0 по построению.
    """

    IRON = "iron"
    BODYWEIGHT = "bodyweight"
    CARDIO = "cardio"


class WeightMode(StrEnum):
    """Как интерпретировать колонку ``weight`` из выгрузки.

    Разбирать приходится потому, что вес тела нигде не выгружается, а
    тренировки на своём теле велись в двух разных конвенциях - и это видно
    по самим числам.

    ``ABSOLUTE``
        Вес как есть: штанга, гантели, блины тренажёра. Складывать ничего
        не нужно. Это большинство упражнений.
    ``VEST_ONLY``
        Записана только добавка: с груди жилет, на живот блит или гантель.
        Таких записей в выгрузках почти нет - у ``Отжиманий`` вообще нет ни
        одной (см. ``rules.PUSHUPS_MAX``), - но режим остаётся верным для
        случая, когда в журнал попадёт жилет: складывать тут нечего.
    ``TOTAL_BODYWEIGHT``
        Записан суммарный вес: собственное тело плюс добавка. У
        ``Подтягивания на перекладине`` значения стоят плотным кластером
        67...82 - это вес тела, а не жилет.
    """

    ABSOLUTE = "absolute"
    VEST_ONLY = "vest_only"
    TOTAL_BODYWEIGHT = "total_bodyweight"


@dataclass(frozen=True, slots=True)
class Group:
    """Двигательный паттерн.

    ``counts_rm`` - считается ли для группы 1RM и производные от него метрики.
    У пресса, подъёма ног, планки и кардио - нет: это работа на своём весе и
    на времени, 1RM в килограммах у них не имеет смысла, а 1RM собственного
    тела в базе всё равно искажается добавкой и разночтениями. Для таких
    групп вес ещё и не переписывается в «суммарный» (см. ``etl._finalize``).
    """

    name: str
    equipment: str
    weight_mode: WeightMode = WeightMode.ABSOLUTE
    timed: bool = False
    counts_rm: bool = True
    mode: Mode = Mode.IRON


