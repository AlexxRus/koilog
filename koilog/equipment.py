#: Профиль по умолчанию для имён, которых нет в таблице. Берётся по группе
#: упражнения: её поле ``equipment`` перечисляет типы снарядов по убыванию
#: частоты, и первый - самый вероятный.
GROUP_FALLBACK: Mapping[str, str] = {
    "тренажёр": _S454,
    "штанга": _B,
    "гантели": _D2,
    "своё тело": _BODY,
}


def _fallback_for(exercise: str | None) -> Profile:
    """Профиль для ненастроенного имени - по группе, а не наугад."""
    group = group_of(exercise)
    equipment = group.equipment
    for key, profile_id in GROUP_FALLBACK.items():
        if key in equipment:
            return PROFILES[profile_id]
    return PROFILES[_BODY]


def profile_of(exercise: str | None, *, vest: bool = False) -> Profile:
    """Профиль инвентаря для упражнения.

    ``vest=True`` включает лестницы, которые по умолчанию выключены (жилет и
    суммарный вес тела с жилетом): без этого флага программа считает, что
    жилета в зале нет.
    """
    profile_id = EXERCISE_PROFILE.get(exercise or "")
    if profile_id is None:
        return _fallback_for(exercise)
    profile = PROFILES[profile_id]
    if profile.opt_in and not vest:
        return PROFILES[_BODY]
    return profile


def weights_of(
    profile: Profile,
    *,
    body_weight: float | None = None,
) -> tuple[float, ...]:
    """Лестница профиля в записанных единицах.

    Для ``bodyweight_ladder`` лестница - это вес тела плюс жилет, поэтому
    нужен текущий вес тела; без него возвращается пустой список, и программа
    честно скажет, что предложить не из чего.
    """
    if not profile.on_bodyweight:
        return profile.weights
    if body_weight is None:
        return ()
    return tuple(round(body_weight + added, 2) for added in profile.weights)


def available_weights(
    exercise: str | None,
    *,
    min_weight: float = 0.0,
    vest: bool = False,
    body_weight: float | None = None,
) -> tuple[float, ...]:
    """Доступные веса для упражнения: что реально можно поставить.

    Пустой кортеж - не ошибка, а ответ «внешнего веса тут нет»: для планки,
    подъёма ног и кардио так и должно быть.
    """
    profile = profile_of(exercise, vest=vest)
    return tuple(
        w for w in weights_of(profile, body_weight=body_weight) if w >= min_weight
    )


def hands_of(exercise: str | None, *, vest: bool = False) -> int:
    """На сколько рук делится записанный вес."""
    return profile_of(exercise, vest=vest).hands


