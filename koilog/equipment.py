def ladder(start: float, stop: float, step: float) -> tuple[float, ...]:
    """Лестница от ``start`` до ``stop`` включительно с шагом ``step``.

    Значения округляются до сотых: ``4.54 * 3 = 13.619999999999998``, а в
    базе вес должен сравниваться с этим числом без потери.
    """
    out: list[float] = []
    count = int(round((stop - start) / step)) + 1
    for i in range(max(count, 0)):
        out.append(round(start + i * step, 2))
    return tuple(out)


@dataclass(frozen=True, slots=True)
class Profile:
    """Лестница весов одного типа снаряда.

    ``weights``
        Веса **в том виде, в каком они записаны в журнале**. Для
        упражнения на две руки это сумма обеих гантелей, поэтому у
        ``dumbbell_2`` это удвоенный список.
    ``hands``
        На сколько рук делится вес снаряда. Это справочное поле отчёта, а не
        множитель в арифметике: лестница уже записана в тех же единицах, что
        и вес в журнале (для гантелей двумя руками - сумма обеих гантелей),
        поэтому ``stats.progression_from_db`` ищет следующий снаряд с
        ``hands = 1``. Значение нужно, чтобы отчёт мог сказать «2 x 20 кг».
    ``exact``
        Лестница известна точно (``dumbbell``, ``vest``, ``barbell``) или
        приблизительно (типовой набор плит вместо конкретного тренажёра).
        У приблизительной лестницы верх границы снизу, чтобы программа не
        улетала за пределы известного набора.
    ``opt_in``
        Лестница включается только по запросу (``--vest``): по умолчанию
        предполагается, что этого снаряда в зале нет.
    ``on_bodyweight``
        Лестница задана как добавка к весу тела, а записана как суммарный
        вес (``total_bodyweight``). Тогда чтение требует текущего веса тела,
        см. ``weights_of``.
    """

