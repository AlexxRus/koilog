def in_stock(weight: float, profile: Profile, *, tol: float = 0.3) -> bool:
    """Есть ли такой вес в лестнице (с допуском на округление)."""
    return any(abs(weight - w) <= tol for w in profile.weights)


def stock_gaps(
    exercise: str,
    weights: list[float],
    *,
    vest: bool = False,
    tol: float = 0.3,
) -> list[float]:
    """Записанные веса, которых нет в инвентаре, по возрастанию.

    Пустой список означает, что журнал и зал совпадают. Непустой - это не
    ошибка загрузки: подходы настоящие, но предложить такой вес вперёд нельзя,
    поэтому ``koilog check`` их показывает.
    """
    profile = profile_of(exercise, vest=vest)
    if not profile.weights:
        return []
    seen: list[float] = []
    for w in sorted(set(round(float(x), 2) for x in weights)):
        if w <= 0:
            continue
        if not in_stock(w, profile, tol=tol) and w not in seen:
            seen.append(w)
    return seen


def unmapped_exercises() -> list[str]:
    """Имена из таксономии, которым не назначен профиль инвентаря.

    Пустой список - условие того, что ``stats.available_weights`` никогда не
    придумает лестницу молча. Проверяется тестом.
    """
    return sorted(name for name in EXERCISE_GROUP if name not in EXERCISE_PROFILE)


