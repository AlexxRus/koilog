"""Инвентарь снарядов: какие веса вообще можно предложить.

Модуль чистый, как ``taxonomy`` и ``rules``: ни БД, ни файлов. Здесь лежит
ответ на вопрос, который история тренировок ответить не может: **какого веса
у меня физически нет**. Программа роста нагрузки имеет право предлагать
только то, что стоит в зале.

Откуда берутся лестницы
----------------------

Гантели, жилет и штанга известны точно:

* **Гантели - 17 пар на руку**: 5, 7, 9, 11, 13, 15, 18, 20, 22, 25, 27, 29,
  32, 34, 36, 38, 40. Это физический инвентарь, а не статистика: гантелей
  на 6.8 или 30 кг не бывает, и предлагать их бессмысленно.
* **Жилет - 0…20 кг с шагом 2**. Включается только по запросу
  (``--vest``): по умолчанию программа считает, что жилета нет, потому что
  в журнале ни одного подхода с жилетом не записано, а придумывать
  переналадку значит предлагать упражнение, которое никто не делал.
* **Штанга - 20…160 с шагом 2.5**: гриф 20 кг плюс блины парами, минимальная
  пара - 1.25 кг, поэтому шаг 2.5. Короткий гриф (гриф EZ, лёгкий гриф) -
  10…40 с тем же шагом.

Тренажёры устроены хуже: у них нет единой лестницы, а набор блинов у
каждого свой. Здесь объявлено **четыре** типовых набора, потому что в этом
зале их и правда четыре, и они покрывают почти все упражнения:

``stack_454``
    Плиты по 20 фунтов: шаг 4.54 кг. Самый частый набор в зале, на нём
    стоят почти все блочные машины. В записях это 13.6, 18.1, 22.7, 27.2,
    31.7, 36.2, 40.8, 45.3, 49.8.
``stack_250``
    Плиты по 2.5 кг. Самки, сгибания ног, разгибания, нижний блок.
``stack_500``
    Плиты по 5 кг. Мелкие машины с коротким рычагом.
``stack_1000``
    Плиты по 10 кг. Самые мелкие: армейский жим, жим ногами, тренажёр Смита.
``stack_2``
    Плиты по 1 кг - есть не во всех залах, но в этом есть, и в журнале ими
    набраны ``Жим штанги стоя`` и ``Становая тяга на прямых ногах``.

Что делать с записями, которых нет в инвентаре
-----------------------------------------------

Ничего не подгонять. В записях есть значения, которых в инвентаре нет
(6.8, 8.8, 11.2, 16.2, 22.5, 26, 30 кг на гантелях; 44 вместо 45.3 в
блоке). Это реальные подходы, и выбрасывать их нельзя - они помечаются как
выбросы только явными правилами из ``rules``. А вот предложить такой вес
вперёд нельзя, поэтому такие строки показываются в ``koilog check`` отдельным
списком: это подсказка «инвентарь и журнал разошлись, посмотри глазами».
"""

