"""Связь нагрузки с болезнями: часы Apple Watch рядом с журналом.

Ядро ``koilog`` отвечает на вопрос «сколько я поднял» (внешняя нагрузка).
Этот подпакет добавляет вторую половину картины - **внутреннюю нагрузку**:
как организм ответил на поднятое (ночной пульс, ВСР, дыхание, температура,
сон). Болезнь здесь - исход, который связывается с расбалансом между
внешней и внутренней нагрузкой.

Модули:

``apple``
    Разбор выгрузки Apple Health (``export.xml``) в таблицы ``aw_*`` той же
    базы. Один проход ``iterparse``: файл не влезает в память.
``load``
    Внешняя нагрузка из ``sets``: тоннаж, sRPE-суррогат, ACWR и его
    EWMA-версия, монотонность и стрейн, регресс e1RM.
``illness``
    Многоуровневые метки эпизодов болезни: ``confirmed`` / ``probable`` /
    ``gap_only`` - из ручной температуры, сигнатуры часов и перерывов.
``ml``
    Признаки и модели. Требует необязательную зависимость ``koilog[ml]``
    (``numpy``, ``scikit-learn``); без неё модуль импортируется, но работать
    не сможет и скажет об этом.
``analysis``
    Готовые срезы рядов для ноутбука (сигнатура эпизодов, спагетти-окна
    перед болезнью, квантили предболезненных дней). Без моделей и без
    сторонних зависимостей.
``text``
    Общее табличное оформление для CLI и ноутбука. Без логики.

Зависимостей от ``numpy``/``scikit-learn`` у остальных модулей нет: ядро
``koilog`` и ``apple``/``load``/``illness``/``analysis``/``text`` держатся
на стандартной библиотеке.
"""

