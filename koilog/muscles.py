def _index() -> dict[str, str]:
    """Ключ сопоставления (normalize + casefold) -> каноническое имя."""
    index: dict[str, str] = {}
    for name in _COMPOSITION:
        key = taxonomy.normalize(name).casefold()
        if key in index and index[key] != name:
            raise ValueError(f"двойное сопоставление: {name} и {index[key]}")
        index[key] = name
    return index


_INDEX: Mapping[str, str] = _index()


def muscles_of(name: str | None) -> MuscleProfile | None:
    """Состав мышц имени; ``None`` — имени нет в справочнике.

    Сопоставление через :func:`taxonomy.normalize`: ё-вариант берёт строку
    словарной записи. Неизвестное имя не получает тихий дефолт —
    вызывающий обязан решить, что с ним делать (как ``groups.mode_of``).
    """
    if not name:
        return None
    canonical = _INDEX.get(taxonomy.normalize(name).casefold())
    return PROFILES.get(canonical) if canonical else None


def unknown() -> list[str]:
    """Имена словаря таксономии без строки справочника (должно быть пусто)."""
    return sorted(set(taxonomy.EXERCISE_GROUP) - set(_COMPOSITION))
